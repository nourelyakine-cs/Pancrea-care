-- ============================================================================
-- MIGRATION : authentification interne (remplace Supabase Auth)
--
-- Deux tables nouvelles :
--   * `compte`                  : identité d'authentification (email + hash du
--                                 mot de passe + rôle + statut de validation).
--                                 Séparée de `medecin` (données cliniques) :
--                                 un compte n'existe pas forcément encore comme
--                                 profil médecin tant qu'il n'est pas validé.
--   * `demande_reinitialisation`: file d'attente gérée par le super admin.
--                                 La plateforme n'a pas de service d'email :
--                                 c'est l'admin qui délivre le jeton.
--
-- Exécuter dans : Supabase Dashboard -> SQL Editor
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- Types énumérés
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 't_role_compte') THEN
        CREATE TYPE public.t_role_compte AS ENUM ('medecin', 'super_admin');
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 't_statut_compte') THEN
        CREATE TYPE public.t_statut_compte AS ENUM ('en_attente', 'actif', 'bloque');
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 't_statut_demande_reinit') THEN
        CREATE TYPE public.t_statut_demande_reinit AS ENUM ('en_attente', 'traitee', 'annulee');
    END IF;
END
$$;

-- ---------------------------------------------------------------------------
-- Table `compte`
--
-- `nom` / `prenom` / `telephone` / `hopital` sont dupliqués depuis `medecin` à
-- dessein. Ils portent l'identité **déclarée à l'inscription**, avant toute
-- validation : sans eux, la file des comptes en attente n'afficherait qu'une
-- liste d'adresses email, et l'admin n'aurait aucun moyen de vérifier qu'un
-- demandeur est bien le médecin qu'il pretend être. Le profil `medecin` n'est
-- créé qu'à l'acceptation, par recopie de ces colonnes.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.compte (
    id_compte                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                     VARCHAR(255) NOT NULL,
    mot_de_passe_hash         TEXT         NOT NULL,
    role                      public.t_role_compte     NOT NULL DEFAULT 'medecin',
    statut                    public.t_statut_compte   NOT NULL DEFAULT 'en_attente',

    -- Identité déclarée à l'inscription (cf. commentaire ci-dessus).
    nom                       VARCHAR(100) NOT NULL,
    prenom                    VARCHAR(100) NOT NULL,
    telephone                 VARCHAR(30),
    hopital                   VARCHAR(150),

    -- NULL tant que le compte n'est pas validé : le profil médecin n'existe
    -- qu'après acceptation par le super admin, donc un compte non validé
    -- n'a aucun accès aux dossiers patients.
    id_medecin                INT,

    -- Vrai si le mot de passe a été posé (ou réinitialisé) par l'admin :
    -- le médecin doit le changer dès sa prochaine connexion.
    doit_changer_mdp          BOOLEAN      NOT NULL DEFAULT FALSE,
    motif_blocage             TEXT,

    -- Anti-force brute : le compte est refusé jusqu'à cette échéance après
    -- MAX_TENTATIVES_CONNEXION échecs consécutifs.
    tentatives_echouees       INT          NOT NULL DEFAULT 0,
    verrouille_jusqu_a        TIMESTAMPTZ,

    date_activation           TIMESTAMPTZ,
    active_par                INT,
    date_derniere_connexion   TIMESTAMPTZ,
    date_creation             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    date_modification         TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_compte_email UNIQUE (email),
    CONSTRAINT fk_compte_medecin   FOREIGN KEY (id_medecin)
        REFERENCES public.medecin(id_medecin) ON DELETE SET NULL,
    CONSTRAINT fk_compte_active_par FOREIGN KEY (active_par)
        REFERENCES public.compte(id_compte) ON DELETE SET NULL,
    -- Un compte d'administration est toujours actif : l'inverse le laisserait
    -- sans aucun moyen de déverrouiller qui que ce soit.
    CONSTRAINT ck_compte_role_admin CHECK (
        role <> 'super_admin' OR statut = 'actif'
    )
);

CREATE INDEX IF NOT EXISTS idx_compte_statut ON public.compte (statut);
CREATE INDEX IF NOT EXISTS idx_compte_medecin ON public.compte (id_medecin);
CREATE INDEX IF NOT EXISTS idx_compte_role ON public.compte (role);

-- ---------------------------------------------------------------------------
-- Table `demande_reinitialisation`
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.demande_reinitialisation (
    id_demande          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compte           INT NOT NULL,
    statut              public.t_statut_demande_reinit NOT NULL DEFAULT 'en_attente',
    -- Empreinte du jeton délivré à l'admin, jamais le jeton lui-même : une
    -- fuite de cette table ne permettrait pas de réinitialiser un compte.
    jeton_hash          TEXT,
    expire_le           TIMESTAMPTZ,
    motif               TEXT,
    traite_par          INT,
    date_demande        TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_traitement     TIMESTAMPTZ,

    CONSTRAINT fk_demande_compte FOREIGN KEY (id_compte)
        REFERENCES public.compte(id_compte) ON DELETE CASCADE,
    CONSTRAINT fk_demande_traite_par FOREIGN KEY (traite_par)
        REFERENCES public.compte(id_compte) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_demande_statut ON public.demande_reinitialisation (statut);
CREATE INDEX IF NOT EXISTS idx_demande_compte ON public.demande_reinitialisation (id_compte);

-- ---------------------------------------------------------------------------
-- Reprise des comptes déjà présents
--
-- Les profils `medecin` créés avant cette migration (via Supabase Auth) n'ont
-- pas de compte : sans ce remplissage, tous les médecins déjà enregistrés
-- seraient exclus de la plateforme du jour au lendemain.
--
-- Ils sont repris BLOQUÉS et sans hash exploitable : leur ancien mot de passe
-- appartenait à Supabase et n'est pas récupérable ici. Un hash bcrypt factice
-- les empêche d'entrer, et l'admin leur délivre un accès par la procédure
-- habituelle — plutôt que de les laisser searing d'un accès dont personne
-- ne connaît le mot de passe.
-- ---------------------------------------------------------------------------
INSERT INTO public.compte (
    email, mot_de_passe_hash, role, statut, nom, prenom, telephone, hopital,
    id_medecin, motif_blocage
)
SELECT
    lower(m.email),
    -- bcrypt d'une valeur aléatoire : impossible à retrouver, donc à utiliser.
    '$2b$12$0e0W8Hk1sT4cQ9vJ6yZf7AeK3pR5nLxTgH2bCdM8uYhZiOaVbQwEr',
    'medecin',
    'bloque',
    m.nom,
    m.prenom,
    m.telephone,
    m.hopital,
    m.id_medecin,
    'Compte repris de l''ancienne authentification : activation requise par l''administration.'
FROM public.medecin m
WHERE NOT EXISTS (
    SELECT 1 FROM public.compte c WHERE c.email = lower(m.email)
);

-- ---------------------------------------------------------------------------
-- Compte super admin initial
--
-- Créé par `python -m app.bootstrap_admin`, jamais d'ici : un mot de passe en
-- clair dans un fichier SQL versionné serait un secret committé. Ce compte
-- est créé directement actif, ce qui est la seule exception à la règle
-- « tout compte passe par la validation » : le super admin valide les comptes,
-- il ne peut donc pas se valider lui-même. La contrainte ck_compte_role_admin
-- l'impose de toute façon.
--
-- L'admin est identifié par role='super_admin' ; aucune colonne dédiée n'est
-- ajoutée, pour ne pas obliger les writers de `medecin` à connaître le rôle.
-- ---------------------------------------------------------------------------

COMMIT;